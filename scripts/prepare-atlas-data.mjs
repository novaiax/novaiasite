import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const destination=path.join(root,'data/atlas-content.json');
if(fs.existsSync(destination))throw new Error('Atlas data already captured; edit its source rather than recapturing rendered pages.');
const plain=s=>String(s||'').replace(/<[^>]*>/g,'').replaceAll('&amp;','&').replaceAll('&nbsp;',' ').trim();
const slugs=['novamemory','novalove','novaformation','novaiaweb','rock-de-strass','novaprompter','novablock','trouvejob'];
const arts=['memory','book','formation','web','rock','prompter','focus','jobs'];
const projects=slugs.map((slug,index)=>{const html=fs.readFileSync(path.join(root,'projets',slug,'index.html'),'utf8');
 const meta=html.match(/<div class="card-meta"><span>(.*?)<\/span><span class="tag">(.*?)<\/span><\/div>/s);
 const title=html.match(/<h1>(.*?)<span class="title-dot">/s)?.[1];
 const description=html.match(/<meta name="description" content="([^"]+)"/s)?.[1];
 const deck=html.match(/<\/h1><p>(.*?)<\/p><\/header>/s)?.[1];
 const aside=html.match(/<aside>.*?<h2>(.*?)<\/h2>(.*?)<\/aside>/s);
 const external=aside?.[2].match(/<a class="button button-light" href="([^"]+)">(.*?)<\/a>/s);
 const article=html.match(/<article class="reading">(.*?)<\/article>/s)?.[1];
 if(!meta||!title||!article)throw new Error('Incomplete original story: '+slug);
 const sections=[...article.matchAll(/<section><h2>(.*?)<\/h2><p>(.*?)<\/p><\/section>/gs)].map(m=>({title:plain(m[1]),text:plain(m[2])}));
 const related=html.match(/<a class="related-link" href="\/projets\/([^"/]+)"/s)?.[1];
 return {slug,name:plain(title),category:plain(meta[1]),status:plain(meta[2]),description:plain(description),deck:plain(deck),lead:plain(aside?.[1]),art:arts[index],external:external?{url:external[1],label:plain(external[2])}:null,sections,related};
});
const parcours=fs.readFileSync(path.join(root,'parcours/index.html'),'utf8');
const about=parcours.match(/<div class="reading">(.*?)<\/div><\/section>/s)?.[1];
const timeline=parcours.match(/<ol class="timeline">(.*?)<\/ol>/s)?.[1];
const practices=[...parcours.matchAll(/<article class="activity" id="([^"]+)">\s*<div class="activity-heading"><p class="activity-focus">(.*?)<\/p><h3>(.*?)<\/h3><\/div>\s*<div class="activity-story">(.*?)<\/div>\s*<\/article>/gs)].map(m=>({id:m[1],focus:plain(m[2]),name:plain(m[3]),html:m[4]}));
const learning=parcours.match(/<dl class="practice-list">(.*?)<\/dl>/s)?.[1];
const privacy=fs.readFileSync(path.join(root,'confidentialite/index.html'),'utf8').match(/<article class="reading legal-copy">(.*?)<\/article>/s)?.[1];
if(!about||!timeline||practices.length!==5||!learning||!privacy)throw new Error('Missing original personal content');
fs.mkdirSync(path.dirname(destination),{recursive:true});
fs.writeFileSync(destination,JSON.stringify({schema_version:1,updated_at:'2026-11-21',projects,parcours:{about,timeline,practices,learning},privacy},null,2));
console.log('Captured '+projects.length+' real project stories and '+practices.length+' personal practices.');
